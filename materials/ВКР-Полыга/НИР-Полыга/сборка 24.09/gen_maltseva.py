def font(run, size):
    run.font.name = "Times New Roman"; run.font.size = Pt(size)
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")

def para(doc, text, size=14, bold=False, indent=True, align=WD_ALIGN_PARAGRAPH.JUSTIFY, spacing=1.5):
    pg = doc.add_paragraph(); pf = pg.paragraph_format
    pf.space_after = Pt(0); pf.space_before = Pt(0); pf.line_spacing = spacing
    if indent: pf.first_line_indent = Cm(1.25)
    pg.alignment = align
    r = pg.add_run(text); r.bold = bold; font(r, size)
    return pg

